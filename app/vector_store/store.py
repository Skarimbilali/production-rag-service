
from pathlib import Path
from typing import Any

import chromadb

from app.core.logger import AppLogger
from app.ingestion.embeddings import EmbeddingService


# Centralized application logger.
logger = AppLogger.get_logger(__name__)


class VectorStoreService:
    """
    Handles vector storage and similarity search using ChromaDB.

    Responsibilities:
        1. Initialize persistent vector database.
        2. Store document chunks and embeddings.
        3. Search similar chunks using English/Roman Urdu queries.
        4. Delete document vectors.
        5. Count stored chunks.
    """

    COLLECTION_NAME = "rag_documents"

    def __init__(self, db_path: str = "data/chroma_db"):
        """
        Initialize the ChromaDB collection.

        Args:
            db_path: Local path where ChromaDB stores its data.
        """
        try:
            # Automatically create database directory.
            Path(db_path).mkdir(parents=True, exist_ok=True)

            # Use persistent storage so data survives restarts.
            self.client = chromadb.PersistentClient(path=db_path)

            # Create collection if it does not already exist.
            self.collection = self.client.get_or_create_collection(
                name=self.COLLECTION_NAME,
                configuration={"hnsw": {"space": "cosine"}}
            )

            logger.info("ChromaDB initialized successfully")

        except Exception:
            logger.exception("ChromaDB initialization failed")
            raise

    def add_chunks(self, chunks: list[dict[str, Any]]) -> int:
        """
        Store document chunks and their embeddings.

        Args:
            chunks: List generated by the chunking service.

        Returns:
            Number of stored chunks.
        """
        if not chunks:
            logger.warning("Empty chunk list received")
            return 0

        try:
            # Extract chunk information.
            ids = [chunk["id"] for chunk in chunks]
            texts = [chunk["text"] for chunk in chunks]

            # Remove None values unsupported by Chroma metadata.
            metadatas = [
                {
                    key: value
                    for key, value in chunk["metadata"].items()
                    if value is not None
                }
                for chunk in chunks
            ]

            # Reuse centralized multilingual embedding service.
            embeddings = EmbeddingService.embed_documents(texts)

            # Save chunks, embeddings and metadata.
            self.collection.upsert(
                ids=ids,
                documents=texts,
                embeddings=embeddings,
                metadatas=metadatas
            )

            logger.info("Stored %d chunks successfully", len(chunks))
            return len(chunks)

        except Exception:
            logger.exception("Failed to store document chunks")
            raise

    def search_chunks(
        self,
        question: str,
        top_k: int = 5
    ) -> list[dict[str, Any]]:
        """
        Retrieve relevant chunks using cosine similarity.

        Args:
            question: English or Roman Urdu question.
            top_k: Maximum number of chunks to retrieve.

        Returns:
            Chunks with text, metadata and similarity score.
        """
        if not isinstance(question, str) or not question.strip():
            raise ValueError("Question cannot be empty")

        if top_k < 1:
            raise ValueError("top_k must be greater than zero")

        try:
            total = self.collection.count()

            if total == 0:
                logger.info("No document chunks available")
                return []

            # Convert the question to an embedding.
            query_embedding = EmbeddingService.embed_query(question)

            # Search the vector database.
            results = self.collection.query(
                query_embeddings=[query_embedding],
                n_results=min(top_k, total),
                include=["documents", "metadatas", "distances"]
            )

            retrieved_chunks = []

            for chunk_id, text, metadata, distance in zip(
                results["ids"][0],
                results["documents"][0],
                results["metadatas"][0],
                results["distances"][0]
            ):
                # Cosine distance converted into similarity.
                similarity = 1.0 - float(distance)

                retrieved_chunks.append({
                    "id": chunk_id,
                    "text": text,
                    "metadata": metadata,
                    "similarity_score": similarity
                })

            logger.info(
                "Retrieved %d relevant chunks",
                len(retrieved_chunks)
            )

            return retrieved_chunks

        except Exception:
            logger.exception("Vector search failed")
            raise

    def delete_document(self, document_id: str) -> int:
        """
        Delete all chunks belonging to a document.

        Returns:
            Number of deleted chunks.
        """
        if not document_id.strip():
            raise ValueError("Document ID cannot be empty")

        try:
            matches = self.collection.get(
                where={"document_id": document_id}
            )

            ids = matches["ids"]

            if ids:
                self.collection.delete(ids=ids)

            logger.info("Deleted %d document chunks", len(ids))
            return len(ids)

        except Exception:
            logger.exception("Document deletion failed")
            raise

    def count_chunks(self) -> int:
        """Return total number of stored chunks."""
        return self.collection.count()
